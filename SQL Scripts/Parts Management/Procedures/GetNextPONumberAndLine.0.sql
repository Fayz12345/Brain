Alter PROCEDURE [dbo].[GetNextPONumberAndLine]
	@IFSSite nvarchar(5),
	@IFSProject nvarchar(10),
	--@SKU nvarchar(25),
	--@IFSLocation nvarchar(20),
	--@IFSCondition nvarchar(50),
	@POVendor nvarchar(50),
	@UserName nvarchar(50),
	@PONumber nvarchar(50) output,
    @POLine [nvarchar](5) Output
AS
BEGIN
set nocount on
Declare @_POLine [nvarchar](5) 
Declare @AutoGeneratedPONumbersID [numeric](18,0)

Select @AutoGeneratedPONumbersID = AutoGeneratedPONumbersID,
       @_POLine = POLine, 
       @PONumber = PONumber from AutoGeneratedPONumbers where IFSSite = @IFSSite
                                                 and IFSProject = @IFSProject
                                                 and POVendor = @POVendor
												 and StatusID = 1

if isnull(@AutoGeneratedPONumbersID,-1) > 0
   begin
   Select @_POLine = POLine, 
          @PONumber = PONumber from AutoGeneratedPONumbers where IFSSite = @IFSSite
                                                 and IFSProject = @IFSProject
                                                 and POVendor = @POVendor
												 and StatusID = 1
   Select @_POLine = @_POLine + 1
   Update AutoGeneratedPONumbers set POLine = @_POLine, LastUpdateDate = getdate(), LastUpdateUser =  @UserName
    where AutoGeneratedPONumbersID = @AutoGeneratedPONumbersID
   Select @POLine = @_POLine
   return
   end


Select Top 1 @PONumber = PONumber from AutoGeneratedPONumbers order by PONumber Desc
if (len(isnull(@PONumber,'')) < 12)
   Select @PONumber = 'BRC000000000'
Declare @Counter numeric(9)
Select @Counter = convert(Numeric(9),Substring(@PONumber,4,9))
Select @Counter = @Counter + 1
Select @POLine = 1
Select @PONumber = 'BRC' + Right('000000000' + convert(nvarchar(9),@Counter),9)

Insert AutoGeneratedPONumbers (
      [IFSSite],
	  [IFSProject],
	  [Sku],
	  [IFSCondition],
	  [IFSLocation],
	  [POVendor],
	  [PONumber],
	  [POLine],
	  [StatusID],
	  [CreatedDate],
	  [CreateUser],
	  [LastUpdateDate],
	  [LastUpdateUser])
Values(@IFSSite,
       @IFSProject,
	   '',
	   '',
	   '',
	   @POVendor,
	   @PONumber,
	   @POLine,
	   1,
	   getdate(),
	   @UserName,
	   getdate(),
	   @UserName
     )

       
Return 0

END





